#!/bin/bash
# Maintainer-only: regenerate sanitized fixtures from the exact base revision.
set -euo pipefail

RB="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BASE="f586d4e6683842085165d808df8a5021f2f67210"
FIXTURES="$RB/tests/fixtures/base-f586d4e"
WORK="$(mktemp -d /tmp/rusty-brain-base-fixture.XXXXXX)"
cleanup() {
    rm -rf -- "$WORK"
}
trap cleanup EXIT

[[ "$(git -C "$RB" cat-file -t "$BASE")" == "commit" ]]
mkdir -p "$WORK/source" "$WORK/home" "$WORK/target" "$FIXTURES"
git -C "$RB" archive "$BASE" | tar -x -C "$WORK/source"
[[ "$(git -C "$WORK/source" rev-parse HEAD 2>/dev/null || true)" == "" ]]

cargo build --offline --manifest-path "$WORK/source/Cargo.toml" \
    --target-dir "$WORK/target"
BIN="$WORK/target/debug/rusty-brain"
export RUSTY_BRAIN_HOME="$WORK/home"
run_base() {
    env -i HOME="$HOME" PATH="$PATH" TMPDIR="${TMPDIR:-/tmp}" LANG=en_US.UTF-8 \
        RUSTY_BRAIN_HOME="$RUSTY_BRAIN_HOME" \
        "$BIN" --project base-fixture "$@"
}

ID_ACTIVE_DUCKDB="$(run_base remember \
    'Base fixture: DuckDB remains local' --tags 'base,duckdb')"
ID_ACTIVE_PARQUET="$(run_base remember \
    'Base fixture: Parquet preserves vectors' --tags 'base,parquet')"
ID_FORGOTTEN="$(run_base remember \
    'Base fixture: forgotten memory stays historical' --tags 'base,forgotten')"
[[ "$(run_base forget "$ID_FORGOTTEN")" == "forgotten $ID_FORGOTTEN" ]]
EXPORT_OUTPUT="$(run_base export)"
BASE_DB="$RUSTY_BRAIN_HOME/projects/base-fixture/brain.db"
BASE_PARQUET="$RUSTY_BRAIN_HOME/projects/base-fixture/exports/${EXPORT_OUTPUT##*/}"
[[ -f "$BASE_DB" && -f "$BASE_PARQUET" ]]
cp "$BASE_DB" "$FIXTURES/brain.db"
cp "$BASE_PARQUET" "$FIXTURES/memories.parquet"

DB_HASH="$(shasum -a 256 "$FIXTURES/brain.db" | cut -d' ' -f1)"
PARQUET_HASH="$(shasum -a 256 "$FIXTURES/memories.parquet" | cut -d' ' -f1)"
cat > "$FIXTURES/README.md" <<EOF
# Sanitized base-revision fixture

Generated by \`scripts/generate_base_fixture.sh\` from \`git archive $BASE\`.
The archived source was built offline; the model was downloaded once into an
isolated temporary \`RUSTY_BRAIN_HOME\`. No user brain or credential was read.
Model: \`AllMiniLML6V2Q\`; schema version: 1; project: \`base-fixture\`.

## Expected rows

| State | ID | Content | Tags |
|---|---|---|---|
| active | $ID_ACTIVE_DUCKDB | Base fixture: DuckDB remains local | base,duckdb |
| active | $ID_ACTIVE_PARQUET | Base fixture: Parquet preserves vectors | base,parquet |
| forgotten | $ID_FORGOTTEN | Base fixture: forgotten memory stays historical | base,forgotten |

## Commands

\`\`\`bash
git archive $BASE
cargo build --offline --manifest-path <archived-source>/Cargo.toml
RUSTY_BRAIN_HOME=<isolated> rusty-brain --project base-fixture remember <content> --tags <tags>
RUSTY_BRAIN_HOME=<isolated> rusty-brain --project base-fixture forget $ID_FORGOTTEN
RUSTY_BRAIN_HOME=<isolated> rusty-brain --project base-fixture export
\`\`\`

## SHA-256 provenance

- Source commit: \`$BASE\`
- \`brain.db\`: \`$DB_HASH\`
- \`memories.parquet\`: \`$PARQUET_HASH\`

The Parquet file contains exactly the two active rows, in \`created_at ASC\`
order. The database retains all three rows, including the forgotten row's
non-null \`deleted_at\`. Final verification reopens both artifacts read-only.
EOF

printf 'base fixture generated: %s\n' "$FIXTURES"
printf 'brain.db sha256 %s\nmemories.parquet sha256 %s\n' "$DB_HASH" "$PARQUET_HASH"
